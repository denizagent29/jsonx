"""jsonxc: schema compiler, converter, validator and binary inspector."""
from __future__ import annotations
import argparse, json, os, struct, sys, time
from . import (JsonxError, parse, encode, decode, compile_file, load_schema, dump)
from .schema import Schema, INTS
from .binary import Reader, HDR

EXIT_OK, EXIT_USAGE, EXIT_INVALID, EXIT_BINARY = 0, 1, 2, 3

def _schema(path):
    if path is None: return None
    data = open(path, "rb").read()
    return load_schema(data) if data[:4] == b"BJXS" else compile_file(path)

def _read(path): return sys.stdin.buffer.read() if path == "-" else open(path, "rb").read()
def _write(path, data):
    if path in (None, "-"): sys.stdout.buffer.write(data if isinstance(data, bytes) else data.encode()); return
    open(path, "wb").write(data if isinstance(data, bytes) else data.encode())

def _fail(e: JsonxError, path=""):
    print(f"{path}{':' if path else ''}{e}", file=sys.stderr)
    return EXIT_BINARY if e.category == "binary" else EXIT_INVALID

def _arr(b: bytes, per_line=16): return ",\n".join("    " + ", ".join(str(x) for x in b[i:i + per_line]) for i in range(0, len(b), per_line))

def tsname(sc, t):
    k = t.kind
    if k in ("u8", "u16", "u32", "i8", "i16", "i32", "f32", "f64"): return "number"
    if k in ("u64", "i64"): return "bigint | number"
    if k == "bool": return "boolean"
    if k == "string": return "string"
    if k == "bytes": return "Uint8Array"
    if k == "any": return "unknown"
    if k in ("struct", "union", "enum"): return sc.types[t.idx].name
    if k == "array": return f"Array<{tsname(sc, t.elem)}>"
    return tsname(sc, t.elem)          # ref<T> navigates transparently

def goname(sc, t):
    k = t.kind
    m = {"u8": "uint8", "u16": "uint16", "u32": "uint32", "u64": "uint64", "i8": "int8", "i16": "int16", "i32": "int32", "i64": "int64", "f32": "float32", "f64": "float64", "bool": "bool", "string": "string", "bytes": "[]byte", "any": "interface{}"}
    if k in m: return m[k]
    if k in ("struct",): return "*" + sc.types[t.idx].name
    if k in ("enum", "union"): return sc.types[t.idx].name
    if k == "array": return "[]" + goname(sc, t.elem)
    return goname(sc, t.elem)

def rsname(sc, t):
    k = t.kind
    if k in ("u8", "u16", "u32", "u64", "i8", "i16", "i32", "i64", "f32", "f64", "bool"): return k
    if k == "string": return "String"
    if k == "bytes": return "Vec<u8>"
    if k == "any": return "jsonx::Doc"
    if k in ("struct", "enum", "union"): return sc.types[t.idx].name
    if k == "array": return f"Vec<{rsname(sc, t.elem)}>"
    return f"jsonx::Id /* ref<{rsname(sc, t.elem)}> */"

def pyname(sc, t):
    k = t.kind
    if k in INTS: return "int"
    if k in ("f32", "f64"): return "float"
    if k == "bool": return "bool"
    if k == "string": return "str"
    if k == "bytes": return "bytes"
    if k == "any": return "Any"
    if k in ("struct", "union", "enum"): return f"'{sc.types[t.idx].name}'"
    if k == "array": return f"List[{pyname(sc, t.elem)}]"
    return pyname(sc, t.elem)

def camel(s): return "".join(p.capitalize() for p in s.split("_"))

def gen(sc: Schema, lang: str, blob: bytes) -> str:
    o = []
    ns = sc.namespace or "schema"
    if lang == "ts":
        o.append(f"// Generated by jsonxc from namespace {ns} (schema version {sc.version}). Do not edit.")
        o.append(f"export const SCHEMA_VERSION = {sc.version};\nexport const SCHEMA_BJXS = new Uint8Array([\n{_arr(blob)}\n]);\n")
        for t in sc.types:
            if t.kind == "enum": o.append(f"export type {t.name} = " + " | ".join(json.dumps(n) for n, _ in t.values) + ";")
            elif t.kind == "union": o.append(f"export type {t.name} = " + " | ".join("{ " + f"{n}: {tsname(sc, ty)}" + " }" for n, _, ty in t.variants) + ";")
            else:
                o.append(f"export interface {t.name} {{")
                for f in t.fields:
                    q = "?" if f.optional else ""; n = " | null" if (f.nullable or f.optional) else ""
                    o.append(f"  {f.name}{q}: {tsname(sc, f.type)}{n};" + ("  // deprecated" if f.deprecated else ""))
                o.append("}")
        o.append("\n// Decode with: import { loadSchema, decode, view } from 'jsonx'; const sc = loadSchema(SCHEMA_BJXS);")
    elif lang == "go":
        o.append(f"// Code generated by jsonxc from namespace {ns} (schema version {sc.version}). DO NOT EDIT.\npackage {ns.split('.')[-1] or 'schema'}\n")
        o.append(f"const SchemaVersion = {sc.version}\n\nvar SchemaBJXS = []byte{{\n{_arr(blob)},\n}}\n")
        for t in sc.types:
            if t.kind == "enum":
                o.append(f"type {t.name} string\n\nconst (")
                o += [f"\t{t.name}{camel(n)} {t.name} = {json.dumps(n)}" for n, _ in t.values]; o.append(")\n")
            elif t.kind == "union":
                o.append(f"// {t.name} holds exactly one variant; the others are nil.\ntype {t.name} struct {{")
                o += [f"\t{camel(n)} *{goname(sc, ty).lstrip('*')}" for n, _, ty in t.variants]; o.append("}\n")
            else:
                o.append(f"type {t.name} struct {{")
                for f in t.fields:
                    ty = goname(sc, f.type)
                    if (f.optional or f.nullable) and not ty.startswith(("*", "[]", "interface")): ty = "*" + ty
                    o.append(f"\t{camel(f.name)} {ty} `jx:\"{f.name}\"`")
                o.append("}\n")
    elif lang == "rust":
        o.append(f"// Generated by jsonxc from namespace {ns} (schema version {sc.version}). Do not edit.\n#![allow(dead_code)]\n")
        o.append(f"pub const SCHEMA_VERSION: usize = {sc.version};\npub const SCHEMA_BJXS: &[u8] = &[\n{_arr(blob)},\n];\n\n/// Load the embedded schema once and reuse it for every request.\npub fn schema() -> jsonx::Schema {{ jsonx::Schema::from_bytes(SCHEMA_BJXS).expect(\"embedded schema is valid\") }}\n")
        for t in sc.types:
            if t.kind == "enum":
                o.append("#[derive(Debug, Clone, PartialEq)]\npub enum " + t.name + " {\n" + "".join(f"    {camel(n)},\n" for n, _ in t.values) + "}\n")
            elif t.kind == "union":
                o.append("#[derive(Debug, Clone)]\npub enum " + t.name + " {\n" + "".join(f"    {camel(n)}({rsname(sc, ty)}),\n" for n, _, ty in t.variants) + "}\n")
            else:
                o.append("#[derive(Debug, Clone)]\npub struct " + t.name + " {")
                for f in t.fields:
                    ty = rsname(sc, f.type); ty = f"Option<{ty}>" if (f.optional or f.nullable) else ty
                    o.append(f"    pub {f.name}: {ty},")
                o.append("}\n")
    elif lang == "python":
        o.append(f"# Generated by jsonxc from namespace {ns} (schema version {sc.version}). Do not edit.\nfrom __future__ import annotations\nfrom dataclasses import dataclass\nfrom typing import Any, List, Optional\n")
        o.append(f"SCHEMA_VERSION = {sc.version}\nSCHEMA_BJXS = bytes([\n{_arr(blob)}\n])\n")
        for t in sc.types:
            if t.kind == "enum": o.append(f"{t.name} = str  # one of: " + ", ".join(n for n, _ in t.values) + "\n")
            elif t.kind == "union": o.append(f"{t.name} = dict  # exactly one key of: " + ", ".join(n for n, _, _ in t.variants) + "\n")
            else:
                o.append(f"@dataclass\nclass {t.name}:")
                for f in t.fields:
                    ty = pyname(sc, f.type); ty = f"Optional[{ty}]" if (f.optional or f.nullable) else ty
                    o.append(f"    {f.name}: {ty}" + (" = None" if (f.optional or f.nullable) else ""))
                o.append("")
    else: raise SystemExit(f"unknown language {lang}")
    return "\n".join(o) + "\n"

def describe(sc: Schema) -> dict:
    def td(t): return {"kind": t.kind, **({"name": sc.types[t.idx].name} if t.kind in ("struct", "enum", "union") else {}), **({"of": td(t.elem)} if t.elem else {})}
    out = {"namespace": sc.namespace, "version": sc.version, "root": None if sc.root is None else sc.types[sc.root].name, "id": f"{sc.id:016x}", "fingerprint": f"{sc.fingerprint():016x}", "types": []}
    for t in sc.types:
        if t.kind == "struct":
            out["types"].append({"kind": "struct", "name": t.name, "fields": [{"name": f.name, "type": td(f.type), "optional": f.optional, "nullable": f.nullable, "since": f.since, "deprecated": f.deprecated, "default": f.default, "attrs": f.attrs} for f in t.fields]})
        elif t.kind == "enum": out["types"].append({"kind": "enum", "name": t.name, "base": t.base, "values": dict(t.values)})
        else: out["types"].append({"kind": "union", "name": t.name, "variants": [{"name": n, "tag": g, "type": td(ty)} for n, g, ty in t.variants]})
    return out

def compat(old: Schema, new: Schema):
    """Evolution check: every field of `old` must exist unchanged in `new`; new fields must be appended with since > old.version."""
    probs = []
    for t in old.types:
        if t.name not in new.by_name: probs.append(f"type {t.name} was removed"); continue
        n = new.types[new.by_name[t.name]]
        if t.kind != n.kind: probs.append(f"{t.name}: kind changed"); continue
        if t.kind == "struct":
            for i, f in enumerate(t.fields):
                if i >= len(n.fields) or n.fields[i].name != f.name: probs.append(f"{t.name}.{f.name}: field removed or reordered (use @deprecated instead)"); continue
                g = n.fields[i]
                if old.type_name(f.type) != new.type_name(g.type): probs.append(f"{t.name}.{f.name}: type changed {old.type_name(f.type)} -> {new.type_name(g.type)}")
                if (f.optional, f.nullable) != (g.optional, g.nullable): probs.append(f"{t.name}.{f.name}: optional/nullable changed (layout change)")
            for g in n.fields[len(t.fields):]:
                if g.since <= old.version: probs.append(f"{t.name}.{g.name}: new field must have @since({old.version + 1}) or later")
        elif t.kind == "enum":
            for nm, v in t.values:
                if (nm, v) not in n.values: probs.append(f"enum {t.name}: member {nm}={v} changed or removed")
            if n.base != t.base and {"u8": 1, "u16": 2, "u32": 4}[n.base] != {"u8": 1, "u16": 2, "u32": 4}[t.base]: probs.append(f"enum {t.name}: storage size changed")
        else:
            for nm, tag, ty in t.variants:
                if (nm, tag) not in [(a, b) for a, b, _ in n.variants]: probs.append(f"union {t.name}: variant {nm}={tag} changed or removed")
    if new.version < old.version: probs.append("schema version decreased")
    return probs

def inspect_blob(data: bytes, sc, hexdump=False) -> str:
    n = len(data); out = []
    if n < HDR: return "too short"
    magic, ver, flags, res, sid, sver, root, length = struct.unpack_from("<3sBHHQIII", data, 0)
    out += [f"BJSONX v{ver}  {n} bytes", f"  flags      0x{flags:04x}{' (crc32 trailer)' if flags & 1 else ''}", f"  schema id  {sid:016x}{' (dynamic)' if sid == 0 else ''}", f"  schema ver {sver}", f"  root       @{root}", f"  length     {length}"]
    try:
        d = decode(data, sc)
        out.append("  decoded    OK"); out.append("  value      " + d.dump())
        if flags & 1: out.append(f"  crc32      {struct.unpack_from('<I', data, n - 4)[0]:08x}")
    except JsonxError as e: out.append(f"  decode     FAILED: {e}")
    if hexdump:
        for i in range(0, n, 16):
            row = data[i:i + 16]; out.append(f"  {i:08x}  {' '.join(f'{b:02x}' for b in row):<48} {''.join(chr(b) if 32 <= b < 127 else '.' for b in row)}")
    return "\n".join(out)

def _json_tree(n):
    """Plain-JSON view of a Document: references become {"$ref": "/canonical/path"}; bytes become base64 strings."""
    import base64
    k = n.kind
    if k == "ref": return {"$ref": n.target.path()}
    if k == "object": return {kk: _json_tree(v) for kk, v in n.items.items()}
    if k == "array": return [_json_tree(v) for v in n.items]
    if k == "bytes": return base64.b64encode(n.value).decode()
    return n.value

def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="jsonxc", description="JSONX schema compiler, converter, validator and inspector")
    sub = ap.add_subparsers(dest="cmd", required=True)
    c = sub.add_parser("compile", help="compile schema.jxs to canonical binary schema (.jxsb)"); c.add_argument("schema"); c.add_argument("-o", "--out"); c.add_argument("--describe", action="store_true", help="print a JSON description instead")
    g = sub.add_parser("gen", help="generate type definitions + embedded schema"); g.add_argument("schema"); g.add_argument("--lang", required=True, choices=["ts", "go", "rust", "python"]); g.add_argument("-o", "--out")
    e = sub.add_parser("encode", help="JSONX text -> BJSONX"); e.add_argument("input"); e.add_argument("-s", "--schema"); e.add_argument("-r", "--root"); e.add_argument("--version", type=int); e.add_argument("--crc", action="store_true"); e.add_argument("-o", "--out")
    d = sub.add_parser("decode", help="BJSONX -> canonical dump / JSON"); d.add_argument("input"); d.add_argument("-s", "--schema"); d.add_argument("--format", choices=["dump", "json"], default="dump"); d.add_argument("-o", "--out")
    v = sub.add_parser("validate", help="validate JSONX text (and optionally against a schema)"); v.add_argument("input"); v.add_argument("-s", "--schema"); v.add_argument("-r", "--root")
    i = sub.add_parser("inspect", help="show header and structure of a .bjsonx file"); i.add_argument("input"); i.add_argument("-s", "--schema"); i.add_argument("--hex", action="store_true")
    k = sub.add_parser("compat", help="check that NEW schema is a compatible evolution of OLD"); k.add_argument("old"); k.add_argument("new")
    b = sub.add_parser("benchmark", help="run the benchmark suite (benchmarks/bench.py)"); b.add_argument("args", nargs="*")
    a = ap.parse_args(argv)
    try:
        if a.cmd == "compile":
            sc = compile_file(a.schema)
            if a.describe: _write(a.out, json.dumps(describe(sc), indent=2, default=str) + "\n")
            else: _write(a.out or os.path.splitext(a.schema)[0] + ".jxsb", sc.to_bytes())
            if not a.describe: print(f"compiled {len(sc.types)} types, schema id {sc.id:016x}, version {sc.version}", file=sys.stderr)
        elif a.cmd == "gen":
            sc = compile_file(a.schema); _write(a.out, gen(sc, a.lang, sc.to_bytes()))
        elif a.cmd == "encode":
            sc = _schema(a.schema); doc = parse(_read(a.input))
            _write(a.out, encode(doc, sc, root=a.root, version=a.version, checksum=a.crc))
        elif a.cmd == "decode":
            doc = decode(_read(a.input), _schema(a.schema))
            if a.format == "json":
                _write(a.out, json.dumps(_json_tree(doc.root), indent=2, ensure_ascii=False) + "\n")
            else: _write(a.out, doc.dump() + "\n")
        elif a.cmd == "validate":
            doc = parse(_read(a.input))
            if a.schema: encode(doc, _schema(a.schema), root=a.root)
            print("ok", file=sys.stderr)
        elif a.cmd == "inspect": print(inspect_blob(_read(a.input), _schema(a.schema), a.hex))
        elif a.cmd == "compat":
            probs = compat(_schema(a.old), _schema(a.new))
            for p in probs: print("incompatible:", p)
            return EXIT_INVALID if probs else EXIT_OK
        elif a.cmd == "benchmark":
            here = os.path.dirname(os.path.abspath(__file__)); import runpy
            sys.argv = ["bench.py"] + a.args; runpy.run_path(os.path.join(here, "..", "..", "..", "benchmarks", "bench.py"), run_name="__main__")
    except JsonxError as ex: return _fail(ex, getattr(a, "input", ""))
    except OSError as ex: print(f"jsonxc: {ex}", file=sys.stderr); return EXIT_USAGE
    return EXIT_OK

if __name__ == "__main__": sys.exit(main())
